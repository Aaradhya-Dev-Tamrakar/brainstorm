def optimize_image_to_webp(src_img_path: Path, dest_dir: Path, slug: str, title: str, quality=88):
    """Resize, optimize, and save both WebP (<250KB) and PNG fallback."""
    dest_dir.mkdir(parents=True, exist_ok=True)
    webp_path = dest_dir / "hero.webp"
    png_path = dest_dir / "hero.png"

    with Image.open(src_img_path) as img:
        img_rgb = img.convert("RGB")
        # Target standard width max 1920
        if img_rgb.width > 1920:
            scale = 1920 / img_rgb.width
            new_size = (1920, int(img_rgb.height * scale))
            img_rgb = img_rgb.resize(new_size, Image.Resampling.LANCZOS)

        # Save WebP
        img_rgb.save(webp_path, format="WEBP", quality=quality, method=6)
        # Save PNG
        img_rgb.save(png_path, format="PNG", optimize=True)

    size_kb = webp_path.stat().st_size / 1024
    print(f"    [+] Generated WebP: {webp_path.name} ({size_kb:.1f} KB, {img_rgb.width}x{img_rgb.height})")

    meta_path = dest_dir / "meta.json"
    meta = {
        "slug": slug,
        "title": title,
        "captured_at": datetime.now().isoformat(),
        "dimensions": f"{img_rgb.width}x{img_rgb.height}",
        "webp_size_kb": round(size_kb, 2),
        "generator": "automate_all_captures.py (PLAN-MEDIA-001)"
    }
    with open(meta_path, "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=2)

    return webp_path


def capture_pdf(recipe):
    """Render PDF report page to high-DPI image using pdftoppm."""
    src = Path(recipe["source_file"])
    if not src.exists():
        print(f"    [-] Source PDF not found: {src}")
        return False

    slug = recipe["slug"]
    dest_dir = PORTFOLIO_ASSETS / slug
    dest_dir.mkdir(parents=True, exist_ok=True)
    temp_prefix = dest_dir / "raw_page"

    page_num = recipe.get("page", 1)
    cmd = [
        str(PDFTOPPM_PATH),
        "-png",
        "-r", "220",
        "-f", str(page_num),
        "-l", str(page_num),
        str(src),
        str(temp_prefix)
    ]
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

    gen_files = list(dest_dir.glob("raw_page-*.png"))
    if not gen_files:
        print(f"    [-] pdftoppm did not produce image for {slug}")
        return False

    raw_img = gen_files[0]
    optimize_image_to_webp(raw_img, dest_dir, slug, recipe["title"])
    raw_img.unlink(missing_ok=True)
    return True


