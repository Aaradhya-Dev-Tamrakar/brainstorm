BS_EPOCH = datetime(1918, 4, 13, tzinfo=timezone.utc)
BS_MONTHS = [
    'Baisakh', 'Jestha', 'Ashadh', 'Shrawan', 'Bhadra', 'Ashwin',
    'Kartik', 'Mangsir', 'Poush', 'Magh', 'Falgun', 'Chaitra'
]
BS_MONTHS_NEP = [
    'वैशाख', 'जेठ', 'असार', 'साउन', 'भदौ', 'असोज',
    'कात्तिक', 'मंसिर', 'पुस', 'माघ', 'फागुन', 'चैत'
]


def ad_to_bs(year: int, month: int, day: int) -> Optional[Tuple[int, int, int, str, str]]:
    """
    Converts Gregorian (A.D.) date to Bikram Sambat (B.S.).
    Returns (bs_year, bs_month, bs_day, month_name_en, month_name_nep) or None.
    """
    try:
        target = datetime(year, month, day, tzinfo=timezone.utc)
    except ValueError:
        return None
        
    remaining = int(round((target - BS_EPOCH).total_seconds() / 86400))
    if remaining < 0:
        return None
        
    for by in range(1975, 2100):
        row = BS_YEARS[by - 1975]
        if remaining >= row[12]:
            remaining -= row[12]
            continue
        for bm in range(12):
            if remaining >= row[bm]:
                remaining -= row[bm]
                continue
            return (by, bm + 1, remaining + 1, BS_MONTHS[bm], BS_MONTHS_NEP[bm])
    return None


def bs_to_ad(by: int, bm: int, bd: int) -> Optional[Tuple[int, int, int]]:
    """
    Converts Bikram Sambat (B.S.) date to Gregorian (A.D.).
    Returns (ad_year, ad_month, ad_day) or None.
    """
    if by < 1975 or by > 2099 or bm < 1 or bm > 12:
        return None
    row = BS_YEARS[by - 1975]
    if bd < 1 or bd > row[bm - 1]:
        return None
        
    days = 0
    for y in range(1975, by):
        days += BS_YEARS[y - 1975][12]
    for m in range(1, bm):
        days += row[m - 1]
    days += (bd - 1)
    
    target = BS_EPOCH + timedelta(days=days)
    return (target.year, target.month, target.day)


def format_dual_date(year_ad: int, month_ad: int, day_ad: int) -> Optional[Dict[str, Any]]:
    """
    Generates standardized dual-calendar metadata dictionary for legal ingestion.
    """
    bs_res = ad_to_bs(year_ad, month_ad, day_ad)
    if not bs_res:
        return None
    by, bm, bd, m_en, m_nep = bs_res
    dt = datetime(year_ad, month_ad, day_ad, tzinfo=timezone.utc)
    return {
        "ad_iso": f"{year_ad:04d}-{month_ad:02d}-{day_ad:02d}",
        "bs_iso": f"{by:04d}-{bm:02d}-{bd:02d}",
        "bs_formatted_en": f"{bd} {m_en} {by} BS",
        "bs_formatted_nep": f"{bd} {m_nep} {by} वि.सं.",
        "epoch_timestamp": int(dt.timestamp())
    }
